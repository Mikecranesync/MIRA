// gen-android-assets.mjs — generate FactoryLM Android launcher icons, splash,
// and Google Play listing graphics from the canonical brand mark (the blue
// rounded square + white "F" used by mira-hub/public/favicon.svg).
//
// The "F" is drawn as geometric paths (not <text>) so rendering is
// deterministic across environments — no font resolution involved.
//
// Run from mira-mobile/:  node tools/gen-android-assets.mjs
// Requires sharp; resolved from ../mira-hub/node_modules (already installed).

import { createRequire } from "module";
import { mkdirSync, writeFileSync } from "fs";
import { join, dirname } from "path";
import { fileURLToPath } from "url";

const here = dirname(fileURLToPath(import.meta.url));
const require = createRequire(join(here, "..", "..", "mira-hub", "package.json"));
const sharp = require("sharp");

const BLUE = "#2563EB";
const RES = join(here, "..", "android", "app", "src", "main", "res");
const STORE = join(here, "..", "store", "play");
mkdirSync(STORE, { recursive: true });

// Geometric "F" centered in a 100×100 box (blocky industrial glyph).
const F_PATHS = `
  <rect x="34" y="22" width="13" height="56" rx="2" fill="white"/>
  <rect x="34" y="22" width="38" height="13" rx="2" fill="white"/>
  <rect x="34" y="46" width="30" height="12" rx="2" fill="white"/>`;

// Full-bleed square icon (legacy launcher + Play 512): blue rounded square, F.
const squareSvg = (size, radiusPct = 18) => `
<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 100 100">
  <rect width="100" height="100" rx="${radiusPct}" fill="${BLUE}"/>
  ${F_PATHS}
</svg>`;

// Play Store icon must be full-square (Play masks it itself): no transparency corners.
const playIconSvg = (size) => `
<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 100 100">
  <rect width="100" height="100" fill="${BLUE}"/>
  ${F_PATHS}
</svg>`;

// Adaptive-icon foreground: glyph inside the 66/108 safe zone on transparency.
const foregroundSvg = (size) => `
<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 108 108">
  <g transform="translate(29,29) scale(0.5)">${F_PATHS}</g>
</svg>`;

// Round legacy icon.
const roundSvg = (size) => `
<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 100 100">
  <circle cx="50" cy="50" r="50" fill="${BLUE}"/>
  ${F_PATHS}
</svg>`;

// Splash: brand blue field, centered mark (works on any screen, scaled by Android).
const splashSvg = (w, h) => `
<svg xmlns="http://www.w3.org/2000/svg" width="${w}" height="${h}" viewBox="0 0 ${w} ${h}">
  <rect width="${w}" height="${h}" fill="${BLUE}"/>
  <g transform="translate(${w / 2 - h * 0.125},${h / 2 - h * 0.125}) scale(${(h * 0.25) / 100})">
    <rect x="0" y="0" width="100" height="100" rx="18" fill="white" opacity="0.12"/>
    ${F_PATHS}
  </g>
</svg>`;

// Feature graphic 1024×500: mark + wordmark drawn as paths-free layout — the
// wordmark uses Arial which renders via libvips on Windows; if the environment
// lacks it the graphic is regenerated by design tooling later (checked output
// is reviewed by a human before upload either way).
const featureSvg = () => `
<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="500" viewBox="0 0 1024 500">
  <rect width="1024" height="500" fill="#0F1E40"/>
  <rect x="0" y="0" width="1024" height="500" fill="${BLUE}" opacity="0.08"/>
  <g transform="translate(96,140) scale(2.2)">
    <rect width="100" height="100" rx="18" fill="${BLUE}"/>
    ${F_PATHS}
  </g>
  <text x="392" y="245" font-family="Arial, Helvetica, sans-serif" font-size="84" font-weight="700" fill="white">FactoryLM</text>
  <text x="396" y="308" font-family="Arial, Helvetica, sans-serif" font-size="26" fill="#B9C6E4">Cited answers from your equipment manuals.</text>
</svg>`;

const png = (svg, w, h, out) =>
  sharp(Buffer.from(svg)).resize(w, h).png().toFile(out).then(() => console.log("wrote", out));

const jobs = [];

// Launcher densities: legacy 48dp base; foreground 108dp base.
const densities = { mdpi: 1, hdpi: 1.5, xhdpi: 2, xxhdpi: 3, xxxhdpi: 4 };
for (const [d, mult] of Object.entries(densities)) {
  const dir = join(RES, `mipmap-${d}`);
  const legacy = Math.round(48 * mult);
  const fg = Math.round(108 * mult);
  jobs.push(png(squareSvg(legacy), legacy, legacy, join(dir, "ic_launcher.png")));
  jobs.push(png(roundSvg(legacy), legacy, legacy, join(dir, "ic_launcher_round.png")));
  jobs.push(png(foregroundSvg(fg), fg, fg, join(dir, "ic_launcher_foreground.png")));
}

// Splash drawables (portrait base + land variants share the centered design).
const splashSets = {
  "drawable": [480, 320],
  "drawable-port-mdpi": [320, 480],
  "drawable-port-hdpi": [480, 800],
  "drawable-port-xhdpi": [720, 1280],
  "drawable-port-xxhdpi": [960, 1600],
  "drawable-port-xxxhdpi": [1280, 1920],
  "drawable-land-mdpi": [480, 320],
  "drawable-land-hdpi": [800, 480],
  "drawable-land-xhdpi": [1280, 720],
  "drawable-land-xxhdpi": [1600, 960],
  "drawable-land-xxxhdpi": [1920, 1280],
};
for (const [dir, [w, h]] of Object.entries(splashSets)) {
  jobs.push(png(splashSvg(w, h), w, h, join(RES, dir, "splash.png")));
}

// Play listing graphics.
jobs.push(png(playIconSvg(512), 512, 512, join(STORE, "play-icon-512.png")));
jobs.push(png(featureSvg(), 1024, 500, join(STORE, "feature-graphic-1024x500.png")));

await Promise.all(jobs);
console.log("done");
