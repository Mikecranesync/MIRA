const FORBIDDEN_PRICES = [
  /\$497/,
  /\$499/,
  /\$97\b/,
  /\$2[–-]5\s*K/i,
  /\$2,000/,
  /\$5,000/,
];

function lockedPriceOk(html: string): boolean {
  const matches = html.match(/\$[\d,]+(?:\.\d+)?/g) ?? [];
  return matches.every((token) => {
    if (token === "$500") return /30-day pilot/i.test(html);
    if (token === "$399") return /\/\s*mo|per month|\/month/i.test(html);
    if (token === "$3,990" || token === "$3990") return /\/\s*yr|per year|\/year/i.test(html);
    return false;
  });
}

describe("public marketing copy — don't-say list and locked prices", () => {
  for (const page of pages) {
    test(`${page.name}: drops the don't-say list and removed claims`, () => {
      for (const rule of DONT_SAY) {
        expect(page.html, `${page.name} still contains: ${rule.label}`).not.toMatch(rule.re);
      }
    });

    test(`${page.name}: shows only the locked price, or no price`, () => {
      for (const re of FORBIDDEN_PRICES) {
        expect(page.html, `${page.name} still contains ${re}`).not.toMatch(re);
      }
      expect(lockedPriceOk(page.html), `${page.name} has a price that is not the locked offer`).toBe(true);
    });
  }

  test("/security and /trust agree on providers, session, and SOC 2", () => {
    const security = pages.find((p) => p.name === "/security")!.html;
    const trust = pages.find((p) => p.name === "/trust")!.html;
    for (const line of [
      "We're not SOC 2 audited yet.",
      "Answers are generated by third-party inference APIs.",
      "Hub sign-in uses a signed session cookie.",
    ]) {
      expect(security).toContain(line);
      expect(trust).toContain(line);
    }
    expect(security).not.toMatch(/Groq|Cerebras|Gemini|Anthropic|OpenAI|OpenRouter/);
    expect(trust).not.toMatch(/Groq|Cerebras|Gemini|Anthropic|OpenAI|OpenRouter/);
    expect(security).not.toMatch(/sessionStorage|expire in 7 days/);
    expect(trust).not.toMatch(/sessionStorage|expire in 7 days/);
  });

  test("primary CTA is Talk to Mike; self-signup is Sign in only", () => {
    const chrome = navbar() + footer();
    expect(chrome).toContain("Talk to Mike");
    expect(chrome).toContain("Sign in");
    expect(chrome).not.toContain("Book $500");
    expect(chrome).not.toContain("Get Started");
    expect(chrome).not.toContain(">CMMS<");
    expect(chrome).not.toContain("/assess");
  });
});
