"""Paired-comparison statistics for retrieval evaluations (stdlib only).

Every function here is deterministic. The bootstrap takes an explicit seed, so a
report can be regenerated byte for byte from the same inputs.
"""

from __future__ import annotations

import math
import random
from collections.abc import Sequence

Z95 = 1.959963984540054


def wilson(k: int, n: int, z: float = Z95) -> tuple[float, float] | None:
    """Wilson score interval for k successes in n trials. None when n == 0."""
    if n == 0:
        return None
    p = k / n
    den = 1 + z * z / n
    centre = (p + z * z / (2 * n)) / den
    half = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / den
    return (max(0.0, centre - half), min(1.0, centre + half))


def mcnemar_exact(b: int, c: int) -> float:
    """Exact two-sided McNemar p-value on the discordant pairs (b, c)."""
    n = b + c
    if n == 0:
        return 1.0
    k = min(b, c)
    tail = sum(math.comb(n, i) for i in range(k + 1)) / 2**n
    return min(1.0, 2 * tail)


def newcombe_paired(a: int, b: int, c: int, d: int, z: float = Z95) -> tuple[float, float] | None:
    """Newcombe (1998) method 10 interval for p2 - p1 with paired binary data.

    Table: a = both succeed, b = arm 1 only, c = arm 2 only, d = both fail.
    The estimate is (c - b) / n, so a positive difference favours arm 2.
    """
    n = a + b + c + d
    if n == 0:
        return None
    p1, p2 = (a + b) / n, (a + c) / n
    l1, u1 = wilson(a + b, n, z)  # type: ignore[misc]
    l2, u2 = wilson(a + c, n, z)  # type: ignore[misc]
    denom = (a + b) * (c + d) * (a + c) * (b + d)
    if denom == 0:
        phi = 0.0
    else:
        num = a * d - b * c
        if num > 0:
            num = max(num - n / 2, 0)
        phi = num / math.sqrt(denom)
    diff = p2 - p1
    dl = math.sqrt(max(0.0, (p2 - l2) ** 2 - 2 * phi * (p2 - l2) * (u1 - p1) + (u1 - p1) ** 2))
    du = math.sqrt(max(0.0, (u2 - p2) ** 2 - 2 * phi * (u2 - p2) * (p1 - l1) + (p1 - l1) ** 2))
    return (max(-1.0, diff - dl), min(1.0, diff + du))


def cluster_bootstrap_diff(
    pairs: Sequence[tuple[str, int, int]], reps: int = 10000, seed: int = 4576
) -> tuple[float, float] | None:
    """Percentile 95% interval for mean(arm2 - arm1), resampling whole clusters.

    pairs: (cluster id, arm1 outcome 0/1, arm2 outcome 0/1). Questions written
    against one manual are not independent, so the manual is resampled, not the
    question.
    """
    clusters: dict[str, list[tuple[int, int]]] = {}
    for cid, x1, x2 in pairs:
        clusters.setdefault(cid, []).append((x1, x2))
    keys = sorted(clusters)
    if len(keys) < 2:
        return None
    rng = random.Random(seed)
    stats = []
    for _ in range(reps):
        tot = n = 0
        for _k in range(len(keys)):
            for x1, x2 in clusters[keys[rng.randrange(len(keys))]]:
                tot += x2 - x1
                n += 1
        stats.append(tot / n)
    stats.sort()
    return (stats[int(0.025 * reps)], stats[int(0.975 * reps) - 1])


def mcnemar_min_discordant(alpha: float = 0.05) -> int:
    """Fewest discordant pairs, all one way, that can reach p < alpha."""
    n = 1
    while mcnemar_exact(0, n) >= alpha:
        n += 1
    return n


def n_to_detect_drop(p0: float, p1: float, alpha: float = 0.05, power: float = 0.8) -> int:
    """Questions needed for a one-sided test to detect a rate falling from p0 to p1.

    Normal approximation for one proportion against a fixed baseline. It is used
    only to state how big an unanswerable set must be; it is not a gate.
    """
    za = _z(1 - alpha)
    zb = _z(power)
    num = za * math.sqrt(p0 * (1 - p0)) + zb * math.sqrt(p1 * (1 - p1))
    return math.ceil((num / (p0 - p1)) ** 2)


def _z(q: float) -> float:
    """Inverse standard-normal CDF by bisection (enough precision for sizing)."""
    lo, hi = -10.0, 10.0
    for _ in range(100):
        mid = (lo + hi) / 2
        if 0.5 * math.erfc(-mid / math.sqrt(2)) < q:
            lo = mid
        else:
            hi = mid
    return (lo + hi) / 2


def percentile(values: Sequence[float], q: float) -> float | None:
    """Nearest-rank percentile (q in 0..100). None for an empty sequence."""
    if not values:
        return None
    s = sorted(values)
    return s[max(0, math.ceil(q / 100 * len(s)) - 1)]
