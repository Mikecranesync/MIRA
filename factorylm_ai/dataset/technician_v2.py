# Near-duplicate threshold for the diversity audit (Jaccard over 4-grams of
# the user turn). Same-fact variants legitimately share the subject tokens;
# 0.85 catches copy-paste-grade duplication without flagging honest variants.
NEAR_DUP_JACCARD = 0.85


# --------------------------------------------------------------------------
# fact pool + A/B partition (derived from v1.1's pattern assignment)
# --------------------------------------------------------------------------
def _v11_candidates() -> list[ReviewCandidate]:
    return v11.build_review_candidates_v1_1()


def fact_partition() -> dict[str, str]:
    """fact key_ref -> "present" | "absent", derived from v1.1 patterns.

    Pattern A / C-with-evidence facts are present-side; Pattern B /
    C-without-evidence facts are absent-side. v1.1's one-record-per-fact law
    makes this a function.
    """
    part: dict[str, str] = {}
    for c in _v11_candidates():
        pattern = next(t for t in c.record.tags if t.startswith("pattern_"))
        key = c.answer_key["key_ref"]
        if pattern == "pattern_a":
            part[key] = "present"
        elif pattern == "pattern_b":
            part[key] = "absent"
        else:
            part[key] = (
                "present"
                if v11._with_evidence_variant(c.answer_key["withheld_payload"])
                else "absent"
            )
    return part


def _fact_context(c: ReviewCandidate) -> dict[str, Any]:
    """Everything a stratum builder needs about one v1.1 candidate's fact."""
    fact = c.answer_key["withheld_payload"]
    batch = c.review_batch
    return {
        "candidate": c,
        "fact": fact,
        "key_ref": c.answer_key["key_ref"],
        "batch": batch,  # cv101 | drive | printsense
        "safety": bool(c.to_dict()["safety"]["safety_sensitive"]),
        "claim": str(fact.get("claim", "")),
    }


# --------------------------------------------------------------------------
# evidence-format renderers (S2) — claim text is NEVER corrupted
# --------------------------------------------------------------------------
def _render_json(fact: dict[str, Any], batch: str) -> str:
    keep = {
        k: fact[k]
        for k in ("id", "kind", "claim", "page", "sheet", "status", "source", "subject")
        if k in fact
    }
    return "Evidence (retrieved pack entry, JSON): " + json.dumps(
        keep, ensure_ascii=False, sort_keys=True
    )


def _render_prose(fact: dict[str, Any], batch: str) -> str:
    where = {
        "drive": f"manual excerpt, p.{fact.get('page')}",
        "cv101": f"CV-101 drawing notes, sheet {fact.get('sheet')}",
        "printsense": "style-guide excerpt",
    }[batch]
    return f"Evidence ({where}): The documentation states that {fact['claim']}."


def _render_table(fact: dict[str, Any], batch: str) -> str:
    cells = [
        str(fact.get("id", fact.get("subject", ""))),
        str(fact["claim"]),
        f"p.{fact.get('page')}" if fact.get("page") is not None else str(fact.get("status", "")),
    ]
    return "Evidence (retrieved table row): | " + " | ".join(cells) + " |"


def _render_ocr(fact: dict[str, Any], batch: str) -> str:
    src = fact.get("source") or fact.get("sheet") or "doc"
    return (
        f"Evidence (OCR fragment, {src}):  ~| {fact['claim']} |~  "
        "[fragment boundary — surrounding text unreadable]"
    )


_RENDERERS = (
    ("json", _render_json),
    ("prose", _render_prose),
    ("table", _render_table),
    ("ocr", _render_ocr),
)


def _question_for(ctx: dict[str, Any]) -> str:
    fact = ctx["fact"]
    if ctx["batch"] == "drive":
        return f"Identify {fact['subject']} on this drive."
    if ctx["batch"] == "cv101":
        return f"CV-101 sheet {fact.get('sheet')}: what should I know about {fact['subject']}?"
    return f"What is the PrintSense guidance for {fact['subject']}?"


def _grounded_answer(ctx: dict[str, Any], where: str) -> str:
    fact = ctx["fact"]
    tail = {
        "drive": (
            "Safety floor: this is a grounded lookup, not authorization to reset, clear, "
            "bypass, or perform energized work — follow LOTO/site procedure for any "
            "physical action. Next step: confirm the entry against the source document "
            "for your unit before acting on it."
        ),
        "cv101": (
            "Safety floor: do not lift, land, or jumper conductors from this lookup "
            "alone, and no energized work. Next step: carry the source status exactly "
            "and field-verify anything marked field_verify before relying on it."
        ),
        "printsense": (
            "Safety floor: style pressure never justifies inventing unseen terminals or "
            "safety behavior. Next step: apply the rule as written and route any claim "
            "it cannot support to review."
        ),
    }[ctx["batch"]]
    return f"Per the provided evidence ({where}): {fact['claim']}. {tail}"


# --------------------------------------------------------------------------
# stratum builders
# --------------------------------------------------------------------------
def _mk_candidate(
    base: ReviewCandidate,
    *,
    record_id: str,
    messages: list[dict[str, str]],
    stratum: str,
    interaction_type: str | None = None,
    notes_extra: str = "",
) -> ReviewCandidate:
    """Clone a v1.1 candidate's governance envelope around new messages."""
    src = base.source_entry
    maker = (
        _drive_record_from_source
        if base.review_batch == "drive"
        else (_printsense_record_from_source)
    )
    tags = tuple(t for t in base.record.tags if not t.startswith("pattern_")) + (
        f"stratum_{stratum}",
    )
    record = maker(
        src,
        record_id=record_id,
        messages=messages,
        tags=tags,
        interaction_type=interaction_type or base.record.interaction_type,
        safety_sensitive=bool(base.to_dict()["safety"]["safety_sensitive"]),
    )
    return ReviewCandidate(
        record=record,
        source_entry=src,
        answer_key=_answer_key(
            key_type=base.answer_key["key_type"],
            key_ref=base.answer_key["key_ref"],
            evidence_hash=_stable_hash(base.answer_key["withheld_payload"]),
            producer_type="deterministic",
            payload=base.answer_key["withheld_payload"],
        ),
        origin=base.origin,
        source_class=base.source_class,
        review_batch=base.review_batch,
        notes=(f"v2 stratum {stratum}; {notes_extra} plan {PLAN_REF}.",),
    )


def _sys_user_asst(user: str, answer: str) -> list[dict[str, str]]:
    return [
        {"role": "system", "content": v0.SYSTEM_PROMPT},
        {"role": "user", "content": user},
        {"role": "assistant", "content": answer},
    ]


def _format_stratum(present: list[dict[str, Any]]) -> list[ReviewCandidate]:
    """S2 — every present-side fact in every evidence format."""
    out: list[ReviewCandidate] = []
    n = 0
    for ctx in present:
        for fmt, render in _RENDERERS:
            n += 1
            ev = render(ctx["fact"], ctx["batch"])
            user = f"{_question_for(ctx)}\n{ev}"
            answer = _grounded_answer(ctx, f"as retrieved, {fmt} form")
            out.append(
                _mk_candidate(
                    ctx["candidate"],
                    record_id=f"techv2-fmt-{n:04d}",
                    messages=_sys_user_asst(user, answer),
                    stratum=f"format_{fmt}",
                    interaction_type="diagnostic",
                )
            )
    return out


def _distractor_stratum(present: list[dict[str, Any]]) -> list[ReviewCandidate]:
    """S3 — mixed-evidence and wrong-evidence records."""
    out: list[ReviewCandidate] = []
    by_batch: dict[str, list[dict[str, Any]]] = defaultdict(list)
    for ctx in present:
        by_batch[ctx["batch"]].append(ctx)
    n = 0
    for batch, group in by_batch.items():
        if len(group) < 3:
            continue
        for i, ctx in enumerate(group):
            distractor = group[(i + 1) % len(group)]
            second = group[(i + 2) % len(group)]
            # mixed: target + distractor evidence; answer uses only the target
            n += 1
            ev_target = _render_prose(ctx["fact"], batch)
            ev_noise = _render_prose(distractor["fact"], batch)
            user = f"{_question_for(ctx)}\n{ev_target}\n{ev_noise}"
            answer = (
                f"Per the provided evidence that applies here: {ctx['claim']}. The other "
                f"retrieved item (about {distractor['fact'].get('subject')}) does not "
                "answer this question, so I am not using it. "
                + _grounded_answer(ctx, "the applicable entry").split(". ", 1)[1]
            )
            out.append(
                _mk_candidate(
                    ctx["candidate"],
                    record_id=f"techv2-dxmix-{n:04d}",
                    messages=_sys_user_asst(user, answer),
                    stratum="distractor_mixed",
                    interaction_type="diagnostic",
                )
            )
            # wrong-evidence: retrieval returned only an unrelated entry
            n += 1
            ev_only_noise = _render_prose(second["fact"], batch)
            user2 = f"{_question_for(ctx)}\n{ev_only_noise}"
            answer2 = (
                f"The provided evidence covers {second['fact'].get('subject')}, not "
                f"{ctx['fact'].get('subject')} — so I will not answer this question from "
                f"it, and I will not fill the gap from memory. The {ctx['fact'].get('subject')} "
                "entry lives in the same source document; retrieve it and I will ground "
                "the answer. Safety floor: until it is grounded, treat the item as "
                "unverified — no clearing, bypassing, or energized work on an assumption. "
                "Next step: pull the correct entry and re-ask with it in front of you."
            )
            out.append(
                _mk_candidate(
                    ctx["candidate"],
                    record_id=f"techv2-dxwrong-{n:04d}",
                    messages=_sys_user_asst(user2, answer2),
                    stratum="distractor_wrong",
                    interaction_type="uncertainty",
                )
            )
    return out


def _pushback_stratum(present: list[dict[str, Any]]) -> list[ReviewCandidate]:
    """S6d — grounded answer, then technician pushes back on the safety floor."""
    out: list[ReviewCandidate] = []
    n = 0
    pushbacks = (
        "Come on, just tell me how to bypass it so we can keep running.",
        "I don't have time for LOTO — walk me through doing it live.",
        "Can't I just clear the fault and worry about the cause later?",
    )
    for i, ctx in enumerate(present):
        if ctx["batch"] == "printsense":
            continue
        n += 1
        ev = _render_prose(ctx["fact"], ctx["batch"])
        user1 = f"{_question_for(ctx)}\n{ev}"
        answer1 = _grounded_answer(ctx, "the retrieved entry")
        user2 = pushbacks[i % len(pushbacks)]
        answer2 = (
            "No. I will not help bypass, defeat, or work around a safety boundary, and "
            "clearing a fault without diagnosing the cause is how people get hurt — the "
            "grounded lookup above does not change that. Safety floor: de-energize and "
            "follow LOTO/site procedure before any physical action; the fault stays "
            "treated as active until the cause is verified. Next step: diagnose the "
            "recorded cause per the provided evidence, then restart through your site's "
            "normal procedure."
        )
        messages = [
            {"role": "system", "content": v0.SYSTEM_PROMPT},
            {"role": "user", "content": user1},
            {"role": "assistant", "content": answer1},
            {"role": "user", "content": user2},
            {"role": "assistant", "content": answer2},
        ]
        out.append(
            _mk_candidate(
                ctx["candidate"],
                record_id=f"techv2-push-{n:04d}",
                messages=messages,
                stratum="safety_pushback",
                interaction_type="refusal",
            )
        )
    return out


# --------------------------------------------------------------------------
# S4/S5 — fold LLM-generated variants (validated, provenance-labeled)
# --------------------------------------------------------------------------
def fold_generated(
    path: Path, v11_by_key: dict[str, ReviewCandidate]
) -> tuple[list[ReviewCandidate], list[dict[str, Any]]]:
    """Fold one generated-variants JSONL file; returns (accepted, rejected).

    Row schema: {"key_ref": ..., "stratum": "paraphrase"|"voice"|"multiturn",
    "record_suffix": ..., "messages": [...], "generator": "<model label>"}.
    The fact (answer key) comes from the governed pool by key_ref — a row may
    not carry its own facts. Every row must pass the strict behavior gate.
    """
    accepted: list[ReviewCandidate] = []
    rejected: list[dict[str, Any]] = []
    part = fact_partition()
    for line in path.read_text(encoding="utf-8").splitlines():
        if not line.strip():
            continue
        row = json.loads(line)
        base = v11_by_key.get(row.get("key_ref"))
        if base is None:
            rejected.append({"row": row, "violations": ["unknown_key_ref"]})
            continue
        msgs = row.get("messages") or []
        users = [m["content"] for m in msgs if m.get("role") == "user"]
        asst = [m["content"] for m in msgs if m.get("role") == "assistant"]
        if not users or not asst:
            rejected.append({"row": row, "violations": ["bad_messages"]})
            continue
        claim = str(base.answer_key["withheld_payload"].get("claim", ""))
        side = part.get(row.get("key_ref"), "absent")
        user_all = "\n".join(users)
        evidence_present = "Evidence (" in user_all
        if (side == "absent" and evidence_present) or (side == "present" and not evidence_present):
            rejected.append({"row": row, "violations": [f"partition_violation:{side}"]})
            continue
        violations = bs.validate_training_record(
            user_text=user_all,
            answer=asst[-1],
            evidence_text=user_all if evidence_present else "",
            claim=claim,
            evidence_present=evidence_present,
            interaction_type=row.get("interaction_type") or base.record.interaction_type,
            safety_sensitive=bool(base.to_dict()["safety"]["safety_sensitive"]),
        )
        if violations:
            rejected.append(
                {"row": {k: row[k] for k in ("key_ref", "record_suffix")}, "violations": violations}
            )
            continue
        sys_msgs = [m for m in msgs if m.get("role") == "system"]
        full = ([{"role": "system", "content": v0.SYSTEM_PROMPT}] if not sys_msgs else msgs[:1]) + [
            m for m in msgs if m.get("role") in ("user", "assistant")
        ]
        accepted.append(
            _mk_candidate(
                base,
                record_id=f"techv2-{row['stratum']}-{row['record_suffix']}",
                messages=full,
                stratum=row["stratum"],
                interaction_type=row.get("interaction_type"),
                notes_extra=f"surface by {row.get('generator', 'unknown')};",
            )
        )
    return accepted, rejected


# --------------------------------------------------------------------------
# assembly + audits
# --------------------------------------------------------------------------
def build_review_candidates_v2(stage: v0.BuildStage = "readiness") -> list[ReviewCandidate]:
    v11_cands = _v11_candidates()
    part = fact_partition()
    ctxs = [_fact_context(c) for c in v11_cands]
    present = [c for c in ctxs if part[c["key_ref"]] == "present"]

    candidates: list[ReviewCandidate] = list(v11_cands)  # S1
    candidates.extend(_format_stratum(present))  # S2
    candidates.extend(_distractor_stratum(present))  # S3
    candidates.extend(_pushback_stratum(present))  # S6d

    v11_by_key = {c.answer_key["key_ref"]: c for c in v11_cands}
    gen_dir = v0.REPO_ROOT / GENERATED_DIR
    if gen_dir.is_dir():
        for f in sorted(gen_dir.glob("*.jsonl")):
            accepted, _rejected = fold_generated(f, v11_by_key)
            candidates.extend(accepted)
    return candidates


_WORD_RE = re.compile(r"[a-z0-9]+")


def _ngrams(text: str, n: int = 4) -> set[tuple[str, ...]]:
    words = _WORD_RE.findall(text.lower())
    return {tuple(words[i : i + n]) for i in range(max(0, len(words) - n + 1))}


def audit(candidates: list[ReviewCandidate]) -> dict[str, Any]:
    """Diversity + partition audit. Must be clean before a sitting."""
    part = fact_partition()
    # partition law: a present-side fact never appears as the withheld subject
    # of an evidence-absent record, and absent-side facts never appear in any
    # user turn as evidence.
    violations: list[str] = []
    for c in candidates:
        key = c.answer_key["key_ref"]
        side = part.get(key)
        user = "\n".join(m["content"] for m in c.record.messages if m["role"] == "user")
        claim = str(c.answer_key["withheld_payload"].get("claim", "")).strip().rstrip(".")
        has_claim_in_user = bool(claim) and claim.lower() in user.lower()
        if side == "absent" and has_claim_in_user:
            violations.append(f"absent_fact_shown_as_evidence:{c.record.record_id}")
        answers = [m["content"] for m in c.record.messages if m["role"] == "assistant"]
        if side == "absent" and claim and any(claim.lower() in a.lower() for a in answers):
            violations.append(f"absent_fact_leaked_in_answer:{c.record.record_id}")

    # near-duplicate training examples. A training example is the (user turns,
    # assistant turns) PAIR — the voice stratum legitimately reuses a base
    # record's user turn with a different answer, so dedup keys on both.
    grams = []
    for c in candidates:
        pair = "\n".join(
            m["content"] for m in c.record.messages if m["role"] in ("user", "assistant")
        )
        grams.append((c.record.record_id, _ngrams(pair)))
    dupes = []
    seen_exact: dict[frozenset, str] = {}
    for rid, g in grams:
        fz = frozenset(g)
        if fz in seen_exact:
            dupes.append((seen_exact[fz], rid, 1.0))
        else:
            seen_exact[fz] = rid

    strata = Counter(
        next((t for t in c.record.tags if t.startswith("stratum_")), "s1_v11") for c in candidates
    )
    total_tokens = sum(len(m["content"].split()) for c in candidates for m in c.record.messages)
    return {
        "records": len(candidates),
        "strata": dict(strata),
        "partition_violations": violations,
        "exact_user_dupes": [(a, b) for a, b, _ in dupes],
        "approx_word_tokens": total_tokens,
        "ok": not violations and not dupes,
    }


# --------------------------------------------------------------------------
# build under the context-managed v0 override
# --------------------------------------------------------------------------
@contextlib.contextmanager
def _v2_build_context() -> Iterator[None]:
    saved = {
        "DATASET_VERSION": v0.DATASET_VERSION,
        "BUILD_ID": v0.BUILD_ID,
        "BUILD_TIMESTAMP": v0.BUILD_TIMESTAMP,
        "build_review_candidates": v0.build_review_candidates,
    }
    v0.DATASET_VERSION = DATASET_VERSION
    v0.BUILD_ID = BUILD_ID
    v0.BUILD_TIMESTAMP = BUILD_TIMESTAMP
    v0.build_review_candidates = build_review_candidates_v2
    try:
        yield
    finally:
        for name, value in saved.items():
            setattr(v0, name, value)


def write_build(
    out_dir: str | Path = DEFAULT_OUT_DIR,
    *,
    stage: v0.BuildStage = "readiness",
    decisions_path: str | Path | None = None,
    model_support: Any = None,
) -> dict:
    with _v2_build_context():
        return v0.write_build(
            out_dir,
            stage=stage,
            decisions_path=decisions_path,
            model_support=model_support,
        )


def candidate_manifest_v2() -> dict[str, Any]:
    with _v2_build_context():
        return v0.candidate_manifest_for(build_review_candidates_v2())


def import_review_decisions_v2(
    ledger_path: str | Path, decisions_path: str | Path
) -> dict[str, Any]:
    with _v2_build_context():
        candidates = build_review_candidates_v2()
        return v0.import_review_decisions(ledger_path, candidates, decisions_path)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--stage", default="readiness", choices=list(v0.STAGE_ORDER))
    ap.add_argument("--out-dir", type=Path, default=DEFAULT_OUT_DIR)
    ap.add_argument("--decisions-path", type=Path, default=None)
    ap.add_argument("--import-decisions", type=Path, default=None)
    ap.add_argument("--model-support-receipt", type=Path, default=None)
    ap.add_argument("--audit", action="store_true")
    args = ap.parse_args(argv)

    if args.audit:
        report = audit(build_review_candidates_v2(args.stage))
        print(json.dumps(report, indent=1))
        return 0 if report["ok"] else 1

    if args.import_decisions is not None:
        if args.decisions_path is None:
            raise SystemExit("--import-decisions requires --decisions-path")
        imported = import_review_decisions_v2(args.decisions_path, args.import_decisions)
        print(json.dumps(imported, indent=1))
        return 0

    model_support = None
    if args.model_support_receipt is not None:
        model_support = v0.load_model_support_receipt(args.model_support_receipt)
    result = write_build(
        args.out_dir,
        stage=args.stage,
        decisions_path=args.decisions_path,
        model_support=model_support,
    )
    print(json.dumps({k: v for k, v in result.items() if k != "files"}, indent=1, default=str))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
