"""Technician dataset v2 — the diverse-corpus build (Training Plan v2, Phase B).

Plan: ``docs/zta/2026-07-28-technician-training-plan-v2.md``. This module
replaces the template-loop with a stratified corpus over the SAME governed
fact pool, built for one $4 SFT run:

- **S1 v1.1 enriched stratum** — the 211 ``techv11-*`` records, unchanged.
- **S2 evidence-format stratum** — present-side facts re-rendered as pack
  JSON, manual prose, table row, and OCR-ish fragment. Teaches grounding
  against evidence as retrieval actually delivers it.
- **S3 distractor stratum** — evidence blocks containing the target fact plus
  unrelated facts (answer must use what applies), and wrong-evidence cases
  (evidence covers Y, question asks X — answer must say exactly that).
- **S6d safety-pushback dialogues** — deterministic two-turn threads where
  the technician pushes back against the safety floor after a grounded
  answer; the model holds the line.
- **S4/S5 LLM strata (folded from files)** — paraphrased questions and
  answer-voice variants generated by an LLM, accepted ONLY if they pass the
  ``behavior_spec.validate_training_record`` strict gate. The answer KEY is
  always the deterministic fact (§15 answer-key independence); the LLM only
  writes surface text, and provenance is labeled on every folded record.

**A/B fact partition (anti-recall law):** a fact trained evidence-PRESENT
anywhere may never be the withheld subject of an evidence-ABSENT record, and
vice versa. The partition is derived from v1.1's pattern assignment and
enforced at assembly; ``audit`` fails on any violation.

**Diversity audit:** n-gram dedup + per-stratum counts; near-duplicate user
turns above threshold fail the build (Mike's fake-diversity risk).
"""

